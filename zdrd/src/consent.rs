//! Consent state machine (Step 2/3). Pure and bus-independent: callers
//! inject the current time and the request id, so every transition is
//! unit-testable without D-Bus, cameras, or models.
//!
//! Invariants:
//! - One pending request per user; a second `begin` is `Busy`.
//! - Requests live 30 s (`DEFAULT_TTL`); after that they are `Expired`.
//! - A denial starts a 5 s per-user cooldown (`DEFAULT_COOLDOWN`) during
//!   which `begin` fails with `Cooldown`.
//! - `respond` is authorized only for uid 0, or for the registered agent
//!   connection (exact unique bus name) whose uid is the request user's uid.
//! - `take_for_verify` consumes an approved request exactly once. A
//!   rejected (not-yet-approved) verify attempt does not consume it.

use std::collections::HashMap;
use std::time::{Duration, Instant};

pub const DEFAULT_TTL: Duration = Duration::from_secs(30);
pub const DEFAULT_COOLDOWN: Duration = Duration::from_secs(5);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Channel {
    Agent,
    Terminal,
}

impl Channel {
    pub fn as_str(&self) -> &'static str {
        match self {
            Channel::Agent => "agent",
            Channel::Terminal => "terminal",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Outcome {
    Approved,
    Denied,
    Expired,
}

impl Outcome {
    pub fn as_str(&self) -> &'static str {
        match self {
            Outcome::Approved => "approved",
            Outcome::Denied => "denied",
            Outcome::Expired => "expired",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ConsentError {
    /// A request is already pending for this user.
    Busy,
    /// The user is inside the post-denial cooldown window.
    Cooldown,
    /// No request with this id (unknown, cancelled, or already consumed).
    Unknown,
    /// The caller is not allowed to perform this action on this request.
    AccessDenied,
    /// The request passed its expiry.
    Expired,
    /// The request exists but has not been approved.
    NotApproved,
}

impl std::fmt::Display for ConsentError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let s = match self {
            ConsentError::Busy => "a request is already pending for this user",
            ConsentError::Cooldown => "user is in post-denial cooldown",
            ConsentError::Unknown => "unknown request",
            ConsentError::AccessDenied => "caller is not authorized for this request",
            ConsentError::Expired => "request expired",
            ConsentError::NotApproved => "request has not been approved",
        };
        f.write_str(s)
    }
}

impl std::error::Error for ConsentError {}

/// Identity of a D-Bus caller, resolved by the service layer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Caller {
    /// Sender unique bus name (e.g. `:1.42`).
    pub sender: String,
    pub uid: u32,
}

#[derive(Debug, Clone)]
struct Agent {
    sender: String,
    uid: u32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum State {
    Awaiting,
    Approved,
    Denied,
    Expired,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Request {
    pub id: String,
    pub user: String,
    pub user_uid: Option<u32>,
    pub service: String,
    pub tty: String,
    pub label: String,
    state: State,
    expires_at: Instant,
}

pub struct Consent {
    requests: HashMap<String, Request>,
    pending_by_user: HashMap<String, String>,
    cooldown_until: HashMap<String, Instant>,
    agents: HashMap<u32, Agent>,
    ttl: Duration,
    cooldown: Duration,
}

impl Default for Consent {
    fn default() -> Self {
        Self::new()
    }
}

impl Consent {
    pub fn new() -> Self {
        Self::with_durations(DEFAULT_TTL, DEFAULT_COOLDOWN)
    }

    pub fn with_durations(ttl: Duration, cooldown: Duration) -> Self {
        Consent {
            requests: HashMap::new(),
            pending_by_user: HashMap::new(),
            cooldown_until: HashMap::new(),
            agents: HashMap::new(),
            ttl,
            cooldown,
        }
    }

    /// Record (or replace) the agent connection for `uid`. One agent per
    /// uid; a new connection from the same uid replaces the old one.
    pub fn register_agent(&mut self, sender: &str, uid: u32) {
        self.agents.insert(
            uid,
            Agent {
                sender: sender.to_string(),
                uid,
            },
        );
    }

    pub fn has_agent_for_uid(&self, uid: u32) -> bool {
        self.agents.contains_key(&uid)
    }

    /// Start a request. `request_id` is generated by the caller (random
    /// 128-bit hex at the service layer).
    pub fn begin(
        &mut self,
        request_id: &str,
        user: &str,
        user_uid: Option<u32>,
        service: &str,
        tty: &str,
        label: &str,
        now: Instant,
    ) -> Result<Channel, ConsentError> {
        self.sweep_user(user, now);
        if let Some(until) = self.cooldown_until.get(user) {
            if now < *until {
                return Err(ConsentError::Cooldown);
            }
            self.cooldown_until.remove(user);
        }
        if self.pending_by_user.contains_key(user) {
            return Err(ConsentError::Busy);
        }
        let channel = match user_uid {
            Some(uid) if self.has_agent_for_uid(uid) => Channel::Agent,
            _ => Channel::Terminal,
        };
        let req = Request {
            id: request_id.to_string(),
            user: user.to_string(),
            user_uid,
            service: service.to_string(),
            tty: tty.to_string(),
            label: label.to_string(),
            state: State::Awaiting,
            expires_at: now + self.ttl,
        };
        self.pending_by_user
            .insert(user.to_string(), request_id.to_string());
        self.requests.insert(request_id.to_string(), req);
        Ok(channel)
    }

    /// Record a decision. Only uid 0, or the registered agent connection
    /// for the request user's uid, may respond.
    pub fn respond(
        &mut self,
        request_id: &str,
        approved: bool,
        caller: &Caller,
        now: Instant,
    ) -> Result<(), ConsentError> {
        // Authorization only needs immutable state; decide it before
        // taking the mutable borrow of the request.
        let authorized = {
            let req = self.requests.get(request_id).ok_or(ConsentError::Unknown)?;
            self.authorized_to_respond(req, caller)
        };
        let req = self
            .requests
            .get_mut(request_id)
            .ok_or(ConsentError::Unknown)?;
        if req.state == State::Awaiting && now >= req.expires_at {
            req.state = State::Expired;
            return Err(ConsentError::Expired);
        }
        if req.state != State::Awaiting {
            return Err(ConsentError::NotApproved);
        }
        if !authorized {
            return Err(ConsentError::AccessDenied);
        }
        if approved {
            req.state = State::Approved;
        } else {
            req.state = State::Denied;
            let user = req.user.clone();
            self.cooldown_until
                .insert(user.clone(), now + self.cooldown);
            self.pending_by_user.remove(&user);
        }
        Ok(())
    }

    fn authorized_to_respond(&self, req: &Request, caller: &Caller) -> bool {
        if caller.uid == 0 {
            return true;
        }
        let Some(req_uid) = req.user_uid else {
            return false;
        };
        if caller.uid != req_uid {
            return false;
        }
        match self.agents.get(&req_uid) {
            Some(agent) => agent.sender == caller.sender && agent.uid == caller.uid,
            None => false,
        }
    }

    /// Current outcome, or `None` while still awaiting a decision.
    /// Denied/expired tombstones are reported until consumed by verify,
    /// cancel, or a sweep; approved requests stay until `take_for_verify`.
    pub fn outcome(
        &mut self,
        request_id: &str,
        now: Instant,
    ) -> Result<Option<Outcome>, ConsentError> {
        let req = self
            .requests
            .get_mut(request_id)
            .ok_or(ConsentError::Unknown)?;
        if matches!(req.state, State::Awaiting | State::Approved) && now >= req.expires_at {
            req.state = State::Expired;
        }
        Ok(match req.state {
            State::Awaiting => None,
            State::Approved => Some(Outcome::Approved),
            State::Denied => Some(Outcome::Denied),
            State::Expired => Some(Outcome::Expired),
        })
    }

    /// Consume an approved request for capture/verify (exactly once).
    /// Not-yet-approved requests are rejected without being consumed.
    pub fn take_for_verify(
        &mut self,
        request_id: &str,
        now: Instant,
    ) -> Result<Request, ConsentError> {
        let req = self
            .requests
            .get_mut(request_id)
            .ok_or(ConsentError::Unknown)?;
        if matches!(req.state, State::Awaiting | State::Approved) && now >= req.expires_at {
            req.state = State::Expired;
        }
        match req.state {
            State::Approved => {
                let req = self
                    .requests
                    .remove(request_id)
                    .ok_or(ConsentError::Unknown)?;
                self.pending_by_user.remove(&req.user);
                Ok(req)
            }
            State::Denied => Err(ConsentError::NotApproved),
            State::Expired => Err(ConsentError::Expired),
            State::Awaiting => Err(ConsentError::NotApproved),
        }
    }

    /// Remove a request if present. Returns whether one was removed.
    pub fn cancel(&mut self, request_id: &str) -> bool {
        match self.requests.remove(request_id) {
            Some(req) => {
                if self.pending_by_user.get(&req.user).map(String::as_str) == Some(request_id) {
                    self.pending_by_user.remove(&req.user);
                }
                true
            }
            None => false,
        }
    }

    /// Drop an expired pending slot for `user` so `begin` is not blocked
    /// forever by a request nobody is watching anymore.
    fn sweep_user(&mut self, user: &str, now: Instant) {
        let Some(id) = self.pending_by_user.get(user).cloned() else {
            return;
        };
        let expired = match self.requests.get(&id) {
            Some(req) => {
                matches!(req.state, State::Expired | State::Denied)
                    || (matches!(req.state, State::Awaiting | State::Approved)
                        && now >= req.expires_at)
            }
            None => true,
        };
        if expired {
            if let Some(req) = self.requests.get_mut(&id) {
                if matches!(req.state, State::Awaiting | State::Approved) {
                    req.state = State::Expired;
                }
            }
            self.pending_by_user.remove(user);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const UID: u32 = 1000;

    fn setup() -> (Consent, Instant) {
        (Consent::new(), Instant::now())
    }

    fn root() -> Caller {
        Caller {
            sender: ":1.1".into(),
            uid: 0,
        }
    }

    fn agent() -> Caller {
        Caller {
            sender: ":1.42".into(),
            uid: UID,
        }
    }

    #[test]
    fn approve_flow() {
        let (mut c, now) = setup();
        c.register_agent(":1.42", UID);
        let ch = c
            .begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        assert_eq!(ch, Channel::Agent);
        assert_eq!(c.outcome("id1", now).expect("outcome"), None);
        c.respond("id1", true, &agent(), now).expect("respond");
        assert_eq!(
            c.outcome("id1", now).expect("outcome"),
            Some(Outcome::Approved)
        );
        let req = c.take_for_verify("id1", now).expect("verify");
        assert_eq!(req.user, "alice");
    }

    #[test]
    fn terminal_channel_without_agent() {
        let (mut c, now) = setup();
        let ch = c
            .begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        assert_eq!(ch, Channel::Terminal);
        // Root (the PAM terminal path) may respond.
        c.respond("id1", true, &root(), now).expect("root respond");
        assert_eq!(
            c.outcome("id1", now).expect("outcome"),
            Some(Outcome::Approved)
        );
    }

    #[test]
    fn deny_flow_starts_cooldown() {
        let (mut c, now) = setup();
        c.register_agent(":1.42", UID);
        c.begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        c.respond("id1", false, &agent(), now).expect("deny");
        assert_eq!(
            c.outcome("id1", now).expect("outcome"),
            Some(Outcome::Denied)
        );
        // Verify on a denied request is not-approved, never a match path.
        assert_eq!(
            c.take_for_verify("id1", now),
            Err(ConsentError::NotApproved)
        );
        // Cooldown: a fresh BeginAuth inside 5 s fails.
        assert_eq!(
            c.begin("id2", "alice", Some(UID), "sudo", "tty1", "true", now),
            Err(ConsentError::Cooldown)
        );
        let later = now + Duration::from_secs(6);
        assert!(c
            .begin("id2", "alice", Some(UID), "sudo", "tty1", "true", later)
            .is_ok());
    }

    #[test]
    fn expiry() {
        let (mut c, now) = setup();
        c.begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        let later = now + Duration::from_secs(31);
        assert_eq!(
            c.outcome("id1", later).expect("outcome"),
            Some(Outcome::Expired)
        );
        assert_eq!(c.take_for_verify("id1", later), Err(ConsentError::Expired));
        assert_eq!(
            c.respond("id1", true, &root(), later),
            Err(ConsentError::NotApproved)
        );
        // The expired slot no longer blocks a new request.
        assert!(c
            .begin("id2", "alice", Some(UID), "sudo", "tty1", "true", later)
            .is_ok());
    }

    #[test]
    fn busy_on_second_request() {
        let (mut c, now) = setup();
        c.begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        assert_eq!(
            c.begin("id2", "alice", Some(UID), "sudo", "tty1", "true", now),
            Err(ConsentError::Busy)
        );
        // A different user is unaffected.
        assert!(c
            .begin("id3", "bob", Some(1001), "sudo", "tty2", "true", now)
            .is_ok());
    }

    #[test]
    fn respond_rejected_from_wrong_sender() {
        let (mut c, now) = setup();
        c.register_agent(":1.42", UID);
        c.begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        // Same uid, different connection: not the registered agent.
        let impostor = Caller {
            sender: ":1.99".into(),
            uid: UID,
        };
        assert_eq!(
            c.respond("id1", true, &impostor, now),
            Err(ConsentError::AccessDenied)
        );
        // Different uid entirely.
        let other = Caller {
            sender: ":1.42".into(),
            uid: 1001,
        };
        assert_eq!(
            c.respond("id1", true, &other, now),
            Err(ConsentError::AccessDenied)
        );
        // The real agent still can.
        c.respond("id1", true, &agent(), now).expect("agent");
    }

    #[test]
    fn agent_replacement_from_same_uid() {
        let (mut c, now) = setup();
        c.register_agent(":1.42", UID);
        c.register_agent(":1.77", UID); // new connection, same uid
        c.begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        assert_eq!(
            c.respond("id1", true, &agent(), now),
            Err(ConsentError::AccessDenied)
        );
        let new_agent = Caller {
            sender: ":1.77".into(),
            uid: UID,
        };
        c.respond("id1", true, &new_agent, now).expect("new agent");
    }

    #[test]
    fn capture_verify_rejected_before_approval() {
        let (mut c, now) = setup();
        c.begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        assert_eq!(
            c.take_for_verify("id1", now),
            Err(ConsentError::NotApproved)
        );
        // Rejection does not consume: approve then verify still works.
        c.respond("id1", true, &root(), now).expect("respond");
        assert!(c.take_for_verify("id1", now).is_ok());
    }

    #[test]
    fn one_shot_consumption() {
        let (mut c, now) = setup();
        c.begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        c.respond("id1", true, &root(), now).expect("respond");
        assert!(c.take_for_verify("id1", now).is_ok());
        assert_eq!(c.take_for_verify("id1", now), Err(ConsentError::Unknown));
        assert_eq!(c.outcome("id1", now), Err(ConsentError::Unknown));
    }

    #[test]
    fn cancel_frees_user() {
        let (mut c, now) = setup();
        c.begin("id1", "alice", Some(UID), "sudo", "tty1", "true", now)
            .expect("begin");
        assert!(c.cancel("id1"));
        assert!(!c.cancel("id1"));
        assert!(c
            .begin("id2", "alice", Some(UID), "sudo", "tty1", "true", now)
            .is_ok());
    }

    #[test]
    fn unknown_request() {
        let (mut c, now) = setup();
        assert_eq!(c.outcome("nope", now), Err(ConsentError::Unknown));
        assert_eq!(
            c.respond("nope", true, &root(), now),
            Err(ConsentError::Unknown)
        );
    }
}
